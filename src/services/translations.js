export const SUPPORTED_LANGUAGES = [
  { code: 'gu-IN', label: 'ગુજરાતી', short: 'GU' },
  { code: 'hi-IN', label: 'हिन्दी', short: 'HI' },
  { code: 'en-IN', label: 'English', short: 'EN' },
  { code: 'mr-IN', label: 'मराठी', short: 'MR' }
];

export const getSavedLanguage = () => {
  try {
    const saved = localStorage.getItem('agroguard_selected_language');
    if (saved && SUPPORTED_LANGUAGES.some(l => l.code === saved)) {
      return saved;
    }
  } catch (e) {
    console.warn('LocalStorage error reading language:', e);
  }
  return 'gu-IN'; // Default to Gujarati
};

export const saveLanguage = (langCode) => {
  try {
    localStorage.setItem('agroguard_selected_language', langCode);
  } catch (e) {
    console.warn('LocalStorage error saving language:', e);
  }
};

